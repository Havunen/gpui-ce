//! Portable SPIR-V for wgpu-hal 29's Vulkan pipeline layouts.
//!
//! Keep this in sync with Vulkan's `create_bind_group_layout`, `create_pipeline_layout`
//! and Naga options when updating WGPU. Passthrough skips WGPU's shader validation.

use super::*;
use naga::back::spv;

pub(super) fn write_shaders(
    out_dir: &std::path::Path,
    base_source: &str,
    subpixel_source: &str,
    reflected: &BTreeMap<&'static str, Vec<ReflectedBinding>>,
) {
    let mut generated = String::from("// @generated by build/vulkan.rs; do not edit.\n");
    generated.push_str("pub const VULKAN_SHADERS: &[VulkanShader] = &[\n");
    // GPUI uses Metal on Apple and WebGPU/GLES on wasm. SPIR-V generation itself is
    // host-independent, including when cross-compiling for Linux from another OS.
    let supported = env::var("CARGO_CFG_TARGET_VENDOR").as_deref() != Ok("apple")
        && !env::var("CARGO_CFG_TARGET_FAMILY")
            .unwrap_or_default()
            .split(',')
            .any(|family| family == "wasm");
    if supported {
        let parse = |source| {
            let module = naga::front::wgsl::parse_str(source).expect("parse Vulkan WGSL");
            let info = naga::valid::Validator::new(
                naga::valid::ValidationFlags::all(),
                naga::valid::Capabilities::all(),
            )
            .validate(&module)
            .expect("validate Vulkan WGSL");
            (module, info)
        };
        let base = parse(base_source);
        let subpixel = parse(subpixel_source);
        for pipeline in shaders::interface::ALL {
            let (data_group, _) = wgpu_data_group(pipeline.data_layout)
                .unwrap_or_else(|| panic!("{} has no WGPU layout", pipeline.label));
            let (module, info) = match pipeline.data_layout {
                shaders::interface::DataLayout::SubpixelSprites => &subpixel,
                _ => &base,
            };
            let options = options([&reflected["GLOBAL_BINDINGS"], &reflected[data_group]]);
            writeln!(
                generated,
                "    VulkanShader {{ label: {:?},",
                pipeline.label
            )
            .unwrap();
            for (field, stage, entry) in [
                ("vertex", naga::ShaderStage::Vertex, pipeline.vertex_entry),
                (
                    "fragment",
                    naga::ShaderStage::Fragment,
                    pipeline.fragment_entry,
                ),
            ] {
                let (module, info) = naga::back::pipeline_constants::process_overrides(
                    module,
                    info,
                    Some((stage, entry)),
                    &Default::default(),
                )
                .unwrap_or_else(|error| panic!("{}: process {entry}: {error}", pipeline.label));
                let words = spv::write_vec(
                    &module,
                    &info,
                    &options,
                    Some(&spv::PipelineOptions {
                        shader_stage: stage,
                        entry_point: entry.to_owned(),
                    }),
                )
                .unwrap_or_else(|error| panic!("{}: emit {entry}: {error}", pipeline.label));
                let file = format!("{}.{field}.spv", pipeline.label);
                let bytes: Vec<_> = words.iter().flat_map(|word| word.to_le_bytes()).collect();
                fs::write(out_dir.join(&file), bytes).expect("write SPIR-V");
                writeln!(generated,
                    "        {field}: VulkanShaderStage {{ entry_point: {entry:?}, words: &spirv_words::<{}>(include_bytes!(concat!(env!(\"OUT_DIR\"), \"/{file}\"))) }},",
                    words.len(),
                ).unwrap();
            }
            generated.push_str("    },\n");
        }
    }
    generated.push_str("];\n");
    fs::write(out_dir.join("vulkan_shaders.rs"), generated).expect("write Vulkan shader table");
}

fn options(groups: [&[ReflectedBinding]; 2]) -> spv::Options<'static> {
    let mut binding_map = spv::BindingMap::default();
    for (group, bindings) in groups.into_iter().enumerate() {
        // wgpu-hal packs each group's bindings in sorted layout order. Use the entire
        // layout, including bindings unused by this stage, to preserve those indices.
        for (packed, binding) in bindings.iter().enumerate() {
            binding_map.insert(
                naga::ResourceBinding {
                    group: group as u32,
                    binding: binding.binding,
                },
                spv::BindingInfo {
                    descriptor_set: group as u32,
                    binding: packed as u32,
                    binding_array_size: None,
                },
            );
        }
    }
    use naga::proc::{BoundsCheckPolicies, BoundsCheckPolicy};
    spv::Options {
        // SPIR-V 1.0 works on every Vulkan version WGPU supports.
        lang_version: (1, 0),
        // WGPU flips the Vulkan viewport itself: ADJUST_COORDINATE_SPACE would flip
        // twice. Avoid LABEL_VARYINGS, which wgpu-hal also disables on Qualcomm.
        flags: spv::WriterFlags::FORCE_POINT_SIZE,
        fake_missing_bindings: false,
        binding_map,
        capabilities: Some(
            [
                spv::Capability::Shader,
                spv::Capability::Matrix,
                spv::Capability::Sampled1D,
                spv::Capability::Image1D,
                spv::Capability::ImageQuery,
                spv::Capability::DerivativeControl,
                spv::Capability::StorageImageExtendedFormats,
            ]
            .into_iter()
            .collect(),
        ),
        // Do not rely on optional device robustness features to protect accesses.
        bounds_check_policies: BoundsCheckPolicies {
            index: BoundsCheckPolicy::Restrict,
            buffer: BoundsCheckPolicy::Restrict,
            image_load: BoundsCheckPolicy::Restrict,
            binding_array: BoundsCheckPolicy::Unchecked,
        },
        zero_initialize_workgroup_memory: spv::ZeroInitializeWorkgroupMemoryMode::Polyfill,
        force_loop_bounding: true,
        use_storage_input_output_16: false,
        ..Default::default()
    }
}
